#!/usr/bin/env bash
# Fresh MariaDB installation only. It never changes an existing MariaDB data directory.
set -Eeuo pipefail
IFS=$'\n\t'

usage() {
  cat <<'EOF'
Usage: sudo ./install-mariadb.sh --role primary|replica --server-id N [options]

Required:
  --role ROLE              primary or replica
  --server-id N            unique positive integer across the three servers

Options:
  --bind-address ADDRESS   listen address (default: 0.0.0.0)
  --port N                 MariaDB port (default: 3306)
  --resume                 continue only an interrupted package installation; never resets data

The script supports Ubuntu 26.04 LTS hosts with systemd and installs the distribution's
mariadb-server package. MariaDB uses Ubuntu's default /var/lib/mariadb location on the OS disk.
EOF
}

role=""; server_id=""; data_dir="/var/lib/mariadb"; resume="false"
bind_address="0.0.0.0"; port="3306"
while (($#)); do
  case "$1" in
    --role) role=${2:?}; shift 2;; --server-id) server_id=${2:?}; shift 2;;
    --bind-address) bind_address=${2:?}; shift 2;; --port) port=${2:?}; shift 2;;
    --resume) resume="true"; shift;;
    -h|--help) usage; exit 0;; *) echo "Unknown argument: $1" >&2; usage >&2; exit 2;;
  esac
done

[[ $EUID -eq 0 ]] || { echo "Run as root (for example: sudo $0 ...)" >&2; exit 1; }
[[ $role == primary || $role == replica ]] || { echo "--role must be primary or replica" >&2; exit 2; }
[[ $server_id =~ ^[1-9][0-9]*$ ]] || { echo "--server-id must be a positive integer" >&2; exit 2; }
[[ $port =~ ^[0-9]+$ && $port -le 65535 ]] || { echo "--port must be 1-65535" >&2; exit 2; }
[[ -f /etc/os-release ]] && . /etc/os-release
[[ ${ID:-} == ubuntu && ${VERSION_ID:-} == 26.04 ]] || { echo "This installer targets Ubuntu 26.04 LTS only." >&2; exit 1; }

main_config=""
mysqld_config="/etc/mysql/mysqld-topology.cnf"
include_line="!include $mysqld_config"
[[ ! -e $mysqld_config ]] || { echo "Refusing: generated mysqld configuration already exists: $mysqld_config" >&2; exit 1; }
if [[ -e $data_dir/mysql && $resume != "true" ]]; then
  echo "Refusing: MariaDB data already exists at $data_dir. Use --resume only after this installer was interrupted after package installation." >&2
  exit 1
fi

apt-get update
apt-get install -y mariadb-server mariadb-client mariadb-backup

# Ubuntu's package owns the main configuration. It may be mariadb.cnf even
# when the my.cnf alternative has not been installed.
for candidate in /etc/mysql/mariadb.cnf /etc/mysql/my.cnf; do
  if [[ -f $candidate ]]; then
    main_config=$candidate
    break
  fi
done
[[ -n $main_config ]] || { echo "MariaDB installed, but no Ubuntu main configuration file was found." >&2; exit 1; }

# Package installation is complete before any MariaDB service command is used.
systemctl stop mariadb
[[ -d $data_dir/mysql ]] || { echo "MariaDB package did not initialize $data_dir as expected." >&2; exit 1; }

umask 027
read_only="OFF"
replica_settings=""
buffer_pool_size="9G"
temp_table_size="32M"
if [[ $role == replica ]]; then
  # More cache is reserved for report reads; keep CPU headroom for report execution.
  buffer_pool_size="10G"
  # Keep application connections from writing while allowing the replica SQL
  # thread to apply events received from the primary.
  read_only="ON"
  replica_settings=$'\n# Replica recovery and bounded parallel apply.\nrelay_log = mariadb-relay\nrelay_log_recovery = ON\nrelay_log_purge = ON\nslave_parallel_threads = 2\nslave_parallel_mode = optimistic'
fi

cat >"$mysqld_config" <<EOF
# Generated by install-mariadb.sh. Change deliberately; this file is not rewritten on reruns.
[mariadb]
bind_address = $bind_address
port = $port
server_id = $server_id

# One primary / read replicas: replication and recovery.
log_bin = mariadb-bin
binlog_format = ROW
log_slave_updates = ON
gtid_strict_mode = ON
binlog_expire_logs_seconds = 1209600

# 4 vCPU / 16 GiB production profile. Keep memory headroom for connections and Linux.
innodb_buffer_pool_size = $buffer_pool_size
innodb_buffer_pool_dump_at_shutdown = ON
innodb_buffer_pool_load_at_startup = ON
innodb_flush_method = O_DIRECT
innodb_io_capacity = 2000
innodb_io_capacity_max = 4000
innodb_log_file_size = 1G

# Durable commits on the primary; replicas retain the same crash-safety posture.
innodb_flush_log_at_trx_commit = 1
sync_binlog = 1
skip_name_resolve = ON
read_only = $read_only$replica_settings

# Bound present-day connection and per-session temporary-memory use.
max_connections = 100
thread_cache_size = 16
max_allowed_packet = 64M
tmp_table_size = $temp_table_size
max_heap_table_size = $temp_table_size

# Disabled until a production baseline establishes what is actually slow.
slow_query_log = OFF
# long_query_time = 10
EOF
chmod 0644 "$mysqld_config"

# Keep the generated server configuration outside Ubuntu's package-managed fragments.
# Append the include only once, preserving all existing distribution includes.
if ! grep -Fqx "$include_line" "$main_config"; then
  printf '\n# Managed by install-mariadb.sh\n%s\n' "$include_line" >>"$main_config"
fi

systemctl enable --now mariadb
mariadb --protocol=socket -e "SELECT @@server_id AS server_id, @@read_only AS read_only, @@gtid_strict_mode AS gtid_strict_mode;"

if [[ $role == primary ]]; then
  echo "Installed fresh MariaDB primary node. Install and seed the replicas before initializing replication on them."
else
  echo "Installed fresh MariaDB replica node. Do not run replication initialization until this replica is seeded from the primary."
fi
