#!/usr/bin/env bash
# Configure a persistent, separately mounted NVMe filesystem for MariaDB temporary work.
set -Eeuo pipefail
IFS=$'\n\t'

usage() {
  cat <<'EOF'
Usage: sudo ./enable-nvme-tempdir.sh --mount /path/to/nvme [--temp-dir /path/to/nvme/mariadb-tmp]

--mount must be the exact, already-mounted root of a persistent NVMe filesystem.
The script creates the temporary workspace, generates /etc/mysql/mysqld-nvme-temp.cnf,
and adds its !include line to Ubuntu's main MariaDB configuration. It does not move /var/lib/mariadb.
EOF
}

nvme_mount=""; temp_dir=""
while (($#)); do
  case "$1" in
    --mount) nvme_mount=${2:?}; shift 2;; --temp-dir) temp_dir=${2:?}; shift 2;;
    -h|--help) usage; exit 0;; *) echo "Unknown argument: $1" >&2; usage >&2; exit 2;;
  esac
done
[[ $EUID -eq 0 ]] || { echo "Run as root." >&2; exit 1; }
[[ -n $nvme_mount ]] || { echo "--mount is required." >&2; usage >&2; exit 2; }
[[ -f /etc/os-release ]] && . /etc/os-release
[[ ${ID:-} == ubuntu && ${VERSION_ID:-} == 26.04 ]] || { echo "This script targets Ubuntu 26.04 LTS only." >&2; exit 1; }
[[ -n $temp_dir ]] || temp_dir="$nvme_mount/mariadb-tmp"

# Confirm this is a real, separately mounted filesystem, rather than silently using the OS disk.
findmnt -T "$nvme_mount" >/dev/null 2>&1 || { echo "NVMe mount is not mounted: $nvme_mount" >&2; exit 1; }
mount_target=$(findmnt -n -o TARGET -T "$nvme_mount")
[[ $mount_target == "$nvme_mount" ]] || { echo "--mount must be the filesystem mount point itself: $nvme_mount" >&2; exit 1; }
[[ $temp_dir == "$nvme_mount"/* ]] || { echo "--temp-dir must be below --mount." >&2; exit 2; }

main_config=""
topology_config="/etc/mysql/mysqld-topology.cnf"
temp_config="/etc/mysql/mysqld-nvme-temp.cnf"
include_line="!include $temp_config"
for candidate in /etc/mysql/mariadb.cnf /etc/mysql/my.cnf; do
  if [[ -f $candidate ]]; then
    main_config=$candidate
    break
  fi
done
[[ -n $main_config && -f $topology_config ]] || { echo "Run install-mariadb.sh first." >&2; exit 1; }
[[ ! -e $temp_config ]] || { echo "Refusing: NVMe temp configuration already exists: $temp_config" >&2; exit 1; }
systemctl is-active --quiet mariadb || { echo "MariaDB is not running; complete installation first." >&2; exit 1; }

# Allow the package's AppArmor profile to access the external NVMe mount when AppArmor is enabled.
apparmor_profile=""
for candidate in /etc/apparmor.d/usr.sbin.mysqld /etc/apparmor.d/usr.sbin.mariadbd; do
  [[ -f $candidate ]] && { apparmor_profile=$candidate; break; }
done
if [[ -n $apparmor_profile ]]; then
  profile_name=$(basename "$apparmor_profile")
  grep -Fq "local/$profile_name" "$apparmor_profile" || {
    echo "AppArmor profile lacks a local include; refusing to weaken or replace it: $apparmor_profile" >&2; exit 1;
  }
  apparmor_local="/etc/apparmor.d/local/$profile_name"
  install -d -m 0755 /etc/apparmor.d/local
  if [[ -e $apparmor_local ]] && grep -Fq '# BEGIN mariadb-nvme-tempdir' "$apparmor_local"; then
    echo "Refusing: AppArmor NVMe temporary-workspace rules already exist." >&2; exit 1
  fi
fi

install -d -o mysql -g mysql -m 0750 "$temp_dir"

if [[ -n $apparmor_profile ]]; then
  cat >>"$apparmor_local" <<EOF

# BEGIN mariadb-nvme-tempdir
$nvme_mount/ r,
$nvme_mount/** rwk,
# END mariadb-nvme-tempdir
EOF
  apparmor_parser -r "$apparmor_profile"
fi

cat >"$temp_config" <<EOF
# Generated by enable-nvme-tempdir.sh. This directory must be on persistent storage.
[mariadb]
# Internal disk temporary tables, filesort work, and SQL temporary files.
tmpdir = $temp_dir
# Replica load work must also survive a restart while replication is active.
slave_load_tmpdir = $temp_dir
# Shared InnoDB temporary tablespace for user-created InnoDB temporary tables.
innodb_temp_data_file_path = $temp_dir/ibtmp1:64M:autoextend
EOF
chmod 0644 "$temp_config"

if ! grep -Fqx "$include_line" "$main_config"; then
  printf '\n# Managed by enable-nvme-tempdir.sh\n%s\n' "$include_line" >>"$main_config"
fi

systemctl restart mariadb
mariadb --protocol=socket -e "SHOW VARIABLES WHERE Variable_name IN ('tmpdir', 'slave_load_tmpdir', 'innodb_temp_data_file_path');"
echo "NVMe temporary workspace enabled at $temp_dir. MariaDB data remains in /var/lib/mariadb."
